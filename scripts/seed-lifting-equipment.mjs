async function seedLiftingEquipment() {
  const connection = await mysql.createConnection({
    host: process.env.DATABASE_URL?.split('@')[1]?.split(':')[0] || 'localhost',
    user: process.env.DATABASE_URL?.split('://')[1]?.split(':')[0] || 'root',
    password: process.env.DATABASE_URL?.split(':')[2]?.split('@')[0] || '',
    database: process.env.DATABASE_URL?.split('/')[3]?.split('?')[0] || 'starpibu',
    ssl: { rejectUnauthorized: false },
  });

  try {
    console.log('💾 리프팅·탄력 탭 12개 장비 등록 중...\n');

    let insertedCount = 0;
    for (const equipment of liftingEquipments) {
      // slug 생성
      const slug = equipment.nameKo
        .toLowerCase()
        .replace(/[^a-z0-9가-힣\s]/g, '')
        .replace(/\s+/g, '-')
        .slice(0, 50);

      try {
        await connection.execute(
          `INSERT INTO equipment3 
          (slug, nameKo, nameEn, nameJa, nameZh, category, descriptionKo, descriptionEn, descriptionJa, descriptionZh, 
           treatmentTimeKo, treatmentTimeEn, treatmentTimeJa, treatmentTimeZh, recoveryPeriodKo, recoveryPeriodEn, recoveryPeriodJa, recoveryPeriodZh,
           badge, imageUrl, isActive, createdAt, updatedAt) 
          VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, NOW(), NOW())`,
          [
            slug,
            equipment.nameKo,
            equipment.nameEn,
            equipment.nameJa,
            equipment.nameZh,
            equipment.category,
            equipment.descriptionKo,
            equipment.descriptionEn,
            equipment.descriptionJa,
            equipment.descriptionZh,
            equipment.treatmentTimeKo,
            equipment.treatmentTimeEn,
            equipment.treatmentTimeJa,
            equipment.treatmentTimeZh,
            equipment.recoveryPeriodKo,
            equipment.recoveryPeriodEn,
            equipment.recoveryPeriodJa,
            equipment.recoveryPeriodZh,
            equipment.badge,
            equipment.imageUrl,
          ]
        );
        console.log(`✅ ${equipment.nameKo}`);
        insertedCount++;
      } catch (e) {
        console.warn(`⚠️  ${equipment.nameKo} - ${e.message}`);
      }
    }

    console.log(`\n✅ 총 ${insertedCount}개 장비 등록 완료`);
  } catch (error) {
    console.error('❌ 오류:', error);
  } finally {
    await connection.end();
  }
}

seedLiftingEquipment();
